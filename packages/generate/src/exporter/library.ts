import type { GeneratedComponent, ParsedDesign } from "../types.js";
import { tokensToCss, tokensToJson, tokensToTailwindTheme } from "./tokens.js";

/**
 * Export the generated library as a set of real, separate files — one
 * component per .tsx, a barrel index, token artifacts, and a README. This is
 * the single source of truth for both the web ZIP download and the CLI's
 * on-disk output, so the two never drift apart.
 */

export interface ExportFile {
  /** Forward-slash relative path inside the bundle, e.g. "components/Button.tsx". */
  path: string;
  content: string;
}

function originNote(c: GeneratedComponent): string {
  switch (c.origin) {
    case "extracted":
      return "extracted from the Figma layer";
    case "inferred":
      return "inferred from the design's structure";
    case "synthesized":
      return "synthesized example (not present in the Figma file)";
  }
}

function buildIndex(components: GeneratedComponent[]): string {
  const lines = components.map(
    (c) => `export { ${c.name} } from "./${c.name}";`,
  );
  return lines.join("\n") + "\n";
}

function buildReadme(design: ParsedDesign): string {
  const extracted = design.components.filter((c) => c.origin !== "synthesized");
  const synthesized = design.components.filter(
    (c) => c.origin === "synthesized",
  );
  const rows = design.components
    .map(
      (c) =>
        `| \`${c.name}\` | ${c.kind} | ${originNote(c)}${c.pageName ? ` (page “${c.pageName}”)` : ""} |`,
    )
    .join("\n");

  return `# ${design.fileName} — component library

Generated by [ForgeUI](https://github.com/Drumil14/ForgeUI) from Figma file \`${design.fileKey}\`
(last modified ${design.lastModified}).

## Contents

| Component | Kind | Origin |
| --- | --- | --- |
${rows}

${
  synthesized.length
    ? `> **Note:** ${synthesized.length} of these (${synthesized
        .map((c) => `\`${c.name}\``)
        .join(", ")}) are synthesized examples built from your design's tokens
> because the Figma file didn't contain that component type. They demonstrate
> what ForgeUI generates — treat them as starting points, not extractions.\n`
    : ""
}
## Usage

These components need **React 18+** and **Tailwind CSS**. They have no other
runtime dependencies.

1. Copy \`components/\` into your project.
2. Merge \`tailwind.config.ts\` into your Tailwind config (it maps the design
   tokens to theme values), or import \`tokens.css\` for plain CSS variables.
3. Import from the barrel:

\`\`\`tsx
import { ${extracted[0]?.name ?? design.components[0]?.name ?? "Button"} } from "./components";
\`\`\`

## Token artifacts

- \`tokens.css\` — CSS custom properties for any framework.
- \`tokens.json\` — structured tokens (Style Dictionary–compatible shape).
- \`tailwind.config.ts\` — the same tokens as a Tailwind theme.
`;
}

/**
 * The full library as separate files. Only files that apply are included
 * (e.g. no tokens.css if the design somehow has zero tokens).
 */
export function exportLibraryFiles(design: ParsedDesign): ExportFile[] {
  const files: ExportFile[] = [];

  for (const c of design.components) {
    files.push({ path: `components/${c.name}.tsx`, content: c.source });
  }
  files.push({
    path: "components/index.ts",
    content: buildIndex(design.components),
  });

  const t = design.tokens;
  const hasTokens =
    t.colors.length ||
    t.typography.length ||
    t.spacing.length ||
    t.radii.length ||
    t.shadows.length;
  if (hasTokens) {
    files.push({ path: "tokens.css", content: tokensToCss(t) });
    files.push({ path: "tokens.json", content: tokensToJson(t) });
    files.push({ path: "tailwind.config.ts", content: tokensToTailwindTheme(t) });
  }

  files.push({ path: "README.md", content: buildReadme(design) });
  return files;
}

/**
 * Legacy single-string bundle (all files concatenated with dividers). Kept for
 * copy-to-clipboard use; downloads should use exportLibraryFiles + ZIP.
 */
export function exportLibrary(design: ParsedDesign): string {
  const divider = (filename: string) =>
    `\n// ${"=".repeat(72)}\n// FILE: ${filename}\n// ${"=".repeat(72)}\n\n`;
  const out: string[] = [
    `/**
 * ${design.fileName} — generated by ForgeUI
 * Source: figma.com/file/${design.fileKey}
 *
 * This is a concatenated preview of the library. For real files, use the ZIP
 * export (web) or \`forgeui generate\` (CLI).
 */
`,
  ];
  for (const f of exportLibraryFiles(design)) {
    out.push(divider(f.path));
    out.push(f.content);
  }
  return out.join("\n");
}

export function exportComponentFile(c: GeneratedComponent): {
  filename: string;
  content: string;
} {
  return { filename: `${c.name}.tsx`, content: c.source };
}
